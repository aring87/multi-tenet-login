"""Write the files the Windows .exe build embeds: the app icon and its version resource.

    py scripts\\make_build_assets.py

Produces, from the same drawing and version number the running app uses so they
never drift apart:

  assets/sentinel-workspace.ico      window, taskbar and Explorer icon (16 to 256 px)
  assets/sentinel-workspace-256.png  the mark for documentation
  assets/version-info.txt            Windows file properties (Details tab) for PyInstaller
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sentinel_app import __version__, brand  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
COMPANY = "ISI Enterprises"
PRODUCT = "Sentinel Workspace"
DESCRIPTION = "Sentinel Workspace for Microsoft Sentinel"

VERSION_INFO = """# UTF-8
# Generated by scripts/make_build_assets.py from sentinel_app.__version__; do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numbers},
    prodvers={numbers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', '{company}'),
        StringStruct('FileDescription', '{description}'),
        StringStruct('FileVersion', '{version}'),
        StringStruct('InternalName', '{product}'),
        StringStruct('LegalCopyright', '{copyright} MIT License.'),
        StringStruct('OriginalFilename', '{product}.exe'),
        StringStruct('ProductName', '{product}'),
        StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version_numbers(version):
    """'2.0.0' -> (2, 0, 0, 0): the four-part numeric version Windows stores."""
    parts = []
    for piece in version.split("."):
        digits = "".join(ch for ch in piece if ch.isdigit())
        parts.append(int(digits) if digits else 0)
    return tuple((parts + [0, 0, 0, 0])[:4])


def copyright_line():
    """The copyright holder as the LICENSE file states it, e.g. 'Copyright (c) 2026 aring87.'"""
    for line in (ROOT / "LICENSE").read_text(encoding="utf-8").splitlines():
        if line.lower().startswith("copyright"):
            return line.strip().rstrip(".") + "."
    return "Copyright (c) " + COMPANY + "."


def version_info(version=__version__):
    return VERSION_INFO.format(numbers=version_numbers(version), version=version, company=COMPANY,
                               product=PRODUCT, description=DESCRIPTION, copyright=copyright_line())


def main():
    ASSETS.mkdir(exist_ok=True)
    (ASSETS / "sentinel-workspace.ico").write_bytes(brand.render_ico())
    (ASSETS / "sentinel-workspace-256.png").write_bytes(brand.render_png(256))
    (ASSETS / "version-info.txt").write_text(version_info(), encoding="utf-8")
    print("Wrote sentinel-workspace.ico, sentinel-workspace-256.png and version-info.txt to", ASSETS)


if __name__ == "__main__":
    main()
